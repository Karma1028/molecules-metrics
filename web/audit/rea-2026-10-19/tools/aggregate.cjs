// Cross-site motion statistics from forensics/<slug>/forensics.json → motion-aggregate.md.
// Answers: which eases/durations/staggers/scroll lerps do winning sites actually use?
// usage: node aggregate.cjs <forensicsDir> <out.md>
const fs = require('fs');
const path = require('path');
const [DIR, OUT] = process.argv.slice(2);

const tally = (m, k, n = 1) => m.set(k, (m.get(k) || 0) + n);
const top = (m, n) => [...m.entries()].sort((a, b) => b[1] - a[1]).slice(0, n);
const pct = (a, p) => { if (!a.length) return '-'; const s = [...a].sort((x, y) => x - y); return Math.round(s[Math.floor((s.length - 1) * p)]); };
const normBez = b => b.replace(/\s+/g, '').replace(/0\./g, '.');

const bez = new Map(), bezSites = new Map(), durCss = [], eases = new Map(), easeSites = new Map();
const tweenDur = [], staggers = [], lerps = [], libs = new Map(), props = new Map(), rows = [];
let n = 0;

for (const slug of fs.readdirSync(DIR)) {
  const f = path.join(DIR, slug, 'forensics.json');
  if (!fs.existsSync(f)) continue;
  const r = JSON.parse(fs.readFileSync(f, 'utf8'));
  if (r.error) continue;
  n++;
  const siteBez = new Set();
  for (const [b, c] of r.css.beziers || []) { const k = normBez(b); tally(bez, k, c); siteBez.add(k); }
  siteBez.forEach(k => tally(bezSites, k));
  for (const [d, c] of r.css.durations || []) { const ms = /ms$/.test(d) ? parseFloat(d) : parseFloat(d) * 1000; if (ms > 0 && ms < 5000) for (let i = 0; i < Math.min(c, 20); i++) durCss.push(ms); }
  for (const l of r.jsLibs || []) tally(libs, l);
  if (!r.scroll.native && r.scroll.lerpEquivalent) lerps.push([slug, r.scroll.lerpEquivalent]);
  const good = (r.tweens || []).filter(t => t.rmse != null && t.rmse <= 0.15);
  const siteEase = new Set();
  for (const t of good) { tally(eases, t.ease); siteEase.add(t.ease); tweenDur.push(t.dur); tally(props, t.prop); }
  siteEase.forEach(e => tally(easeSites, e));
  // stagger: consecutive starts of same el-class/prop/ease within 300ms
  const byKey = new Map();
  for (const t of good) { const k = [t.el.replace(/@.*/, ''), t.prop, t.ease].join('|'); (byKey.get(k) || byKey.set(k, []).get(k)).push(t.start); }
  for (const s of byKey.values()) { s.sort((a, b) => a - b); for (let i = 1; i < s.length; i++) { const d = s[i] - s[i - 1]; if (d > 5 && d < 300) staggers.push(d); } }
  const domEase = top(new Map(good.map(t => [t.ease, good.filter(x => x.ease === t.ease).length])), 1)[0];
  rows.push(`| ${slug} | ${(r.jsLibs || []).slice(0, 4).join(', ') || '-'} | ${r.scroll.native ? 'native' : r.scroll.lerpEquivalent} | ${good.length}/${(r.tweens || []).length} | ${domEase ? domEase[0] : '-'} | ${pct(good.map(t => t.dur), 0.5)} | ${r.canvasCtx.length ? r.canvasCtx.map(c => c[1]).join('+') : '-'} |`);
}

const L = [`# Cross-site motion aggregate — ${n} sites (generated by tools/aggregate.cjs)`,
  '', 'Tweens counted only when the fitted ease has rmse ≤ 0.15. Durations in ms.', '',
  '## JS tween eases (by number of sites using it, then tween count)',
  ...top(easeSites, 12).map(([e, s]) => `- ${e}: ${s} sites, ${eases.get(e)} tweens`),
  '', `## JS tween durations: p25 ${pct(tweenDur, .25)} · median ${pct(tweenDur, .5)} · p75 ${pct(tweenDur, .75)} · p90 ${pct(tweenDur, .9)} (n=${tweenDur.length})`,
  `## Stagger between sibling tweens: p25 ${pct(staggers, .25)} · median ${pct(staggers, .5)} · p75 ${pct(staggers, .75)} (n=${staggers.length})`,
  `## Tweened properties: ${top(props, 10).map(([p, c]) => `${p}×${c}`).join(', ')}`,
  '', '## CSS cubic-beziers (by number of sites)',
  ...top(bezSites, 15).map(([b, s]) => `- ${b}: ${s} sites, ${bez.get(b)} uses`),
  '', `## CSS durations: p25 ${pct(durCss, .25)} · median ${pct(durCss, .5)} · p75 ${pct(durCss, .75)} (n=${durCss.length})`,
  `## Smooth-scroll lerp (non-native sites, ${lerps.length}/${n}): ${lerps.map(([s, l]) => `${s} ${l}`).join(', ') || 'none'}`,
  `## Libraries: ${top(libs, 20).map(([l, c]) => `${l}×${c}`).join(', ')}`,
  '', '## Per site', '| site | libs | scroll lerp | fitted/all tweens | dominant ease | median dur | canvas |', '|---|---|---|---|---|---|---|', ...rows];
fs.writeFileSync(OUT, L.join('\n'));
